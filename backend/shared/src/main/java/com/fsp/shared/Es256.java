package com.fsp.shared;

import com.fasterxml.jackson.databind.ObjectMapper;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.KeyFactory;
import java.security.KeyPair;
import java.security.KeyPairGenerator;
import java.security.Signature;
import java.security.interfaces.ECPrivateKey;
import java.security.interfaces.ECPublicKey;
import java.security.spec.ECGenParameterSpec;
import java.security.spec.PKCS8EncodedKeySpec;
import java.util.Base64;
import java.util.Map;

/**
 * ES256 (P-256) helpers for FAPI 2.0 machine clients and the gateway:
 * compact-JWS signing (client assertions, DPoP proofs, actor assertions) and PKCS#8 PEM
 * key loading. Keys are files (mounted / generated by the dev PKI script) — never baked in.
 */
public final class Es256 {

    private static final ObjectMapper MAPPER = new ObjectMapper();
    private static final Base64.Encoder B64 = Base64.getUrlEncoder().withoutPadding();

    private Es256() {}

    /** Sign {@code header}.{@code payload} as a compact JWS (raw r||s signature). */
    public static String sign(Map<String, Object> header, Map<String, Object> payload, ECPrivateKey key) {
        try {
            String input = B64.encodeToString(MAPPER.writeValueAsBytes(header)) + "."
                + B64.encodeToString(MAPPER.writeValueAsBytes(payload));
            Signature sig = Signature.getInstance("SHA256withECDSA");
            sig.initSign(key);
            sig.update(input.getBytes(StandardCharsets.US_ASCII));
            return input + "." + B64.encodeToString(JwtService.ecdsaDerToJws(sig.sign(), 32));
        } catch (Exception e) {
            throw new IllegalStateException("ES256 signing failed", e);
        }
    }

    /** b64url(SHA-256(ascii)) — DPoP `ath` for an access token. */
    public static String sha256B64(String s) {
        try {
            return B64.encodeToString(java.security.MessageDigest.getInstance("SHA-256")
                .digest(s.getBytes(StandardCharsets.US_ASCII)));
        } catch (java.security.NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }

    /**
     * Load a P-256 key pair from a PKCS#8 PEM file; when the file does not exist and
     * {@code createIfMissing}, generate one and write it with owner-only permissions
     * (dev bootstrap — the same file is then reused across restarts).
     */
    public static KeyPair loadOrCreate(Path pem, boolean createIfMissing) {
        try {
            if (!Files.exists(pem)) {
                if (!createIfMissing) throw new IllegalStateException("key file missing: " + pem);
                KeyPairGenerator kpg = KeyPairGenerator.getInstance("EC");
                kpg.initialize(new ECGenParameterSpec("secp256r1"));
                KeyPair kp = kpg.generateKeyPair();
                Files.createDirectories(pem.toAbsolutePath().getParent());
                String body = Base64.getMimeEncoder(64, "\n".getBytes(StandardCharsets.US_ASCII))
                    .encodeToString(kp.getPrivate().getEncoded());
                Files.writeString(pem, "-----BEGIN PRIVATE KEY-----\n" + body + "\n-----END PRIVATE KEY-----\n");
                try {
                    Files.setPosixFilePermissions(pem, java.nio.file.attribute.PosixFilePermissions.fromString("rw-------"));
                } catch (UnsupportedOperationException ignored) {
                    // non-POSIX file system
                }
                return kp;
            }
            String text = Files.readString(pem)
                .replaceAll("-----(BEGIN|END) (EC )?PRIVATE KEY-----", "").replaceAll("\\s", "");
            KeyFactory kf = KeyFactory.getInstance("EC");
            ECPrivateKey priv = (ECPrivateKey) kf.generatePrivate(new PKCS8EncodedKeySpec(Base64.getDecoder().decode(text)));
            return new KeyPair(publicOf(priv), priv);
        } catch (IOException | java.security.GeneralSecurityException e) {
            throw new IllegalStateException("cannot load EC key " + pem, e);
        }
    }

    /** Derive the public point Q = d·G for a P-256 private key. */
    public static ECPublicKey publicOf(ECPrivateKey priv) throws java.security.GeneralSecurityException {
        var spec = priv.getParams();
        java.security.spec.ECPoint q = multiply(spec.getGenerator(), priv.getS(), spec);
        return (ECPublicKey) KeyFactory.getInstance("EC").generatePublic(new java.security.spec.ECPublicKeySpec(q, spec));
    }

    // Affine double-and-add over the prime field — only used once at key load.
    private static java.security.spec.ECPoint multiply(java.security.spec.ECPoint g, java.math.BigInteger k,
                                                       java.security.spec.ECParameterSpec spec) {
        java.math.BigInteger p = ((java.security.spec.ECFieldFp) spec.getCurve().getField()).getP();
        java.math.BigInteger a = spec.getCurve().getA();
        java.security.spec.ECPoint r = java.security.spec.ECPoint.POINT_INFINITY;
        java.security.spec.ECPoint q = g;
        for (int i = k.bitLength() - 1; i >= 0; i--) {
            r = add(r, r, p, a);
            if (k.testBit(i)) r = add(r, q, p, a);
        }
        return r;
    }

    private static java.security.spec.ECPoint add(java.security.spec.ECPoint s, java.security.spec.ECPoint t,
                                                  java.math.BigInteger p, java.math.BigInteger a) {
        if (s.equals(java.security.spec.ECPoint.POINT_INFINITY)) return t;
        if (t.equals(java.security.spec.ECPoint.POINT_INFINITY)) return s;
        java.math.BigInteger x1 = s.getAffineX(), y1 = s.getAffineY(), x2 = t.getAffineX(), y2 = t.getAffineY();
        java.math.BigInteger l;
        if (x1.equals(x2)) {
            if (!y1.equals(y2) || y1.signum() == 0) return java.security.spec.ECPoint.POINT_INFINITY;
            l = x1.pow(2).multiply(java.math.BigInteger.valueOf(3)).add(a)
                .multiply(y1.shiftLeft(1).modInverse(p)).mod(p);
        } else {
            l = y2.subtract(y1).multiply(x2.subtract(x1).modInverse(p)).mod(p);
        }
        java.math.BigInteger x3 = l.pow(2).subtract(x1).subtract(x2).mod(p);
        java.math.BigInteger y3 = l.multiply(x1.subtract(x3)).subtract(y1).mod(p);
        return new java.security.spec.ECPoint(x3, y3);
    }
}
